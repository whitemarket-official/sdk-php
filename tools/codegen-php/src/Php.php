<?php

declare(strict_types=1);

namespace WhiteMarket\Sdk\Tools\Codegen;

/**
 * Small helpers for emitting PHP source: names, PHPDoc text, nullable types.
 */
final class Php
{
    /** Lower-cased words PHP does not accept as a class name. */
    private const RESERVED_CLASS_NAMES = [
        'abstract', 'and', 'array', 'as', 'bool', 'break', 'callable', 'case', 'catch', 'class', 'clone', 'const',
        'continue', 'declare', 'default', 'do', 'echo', 'else', 'elseif', 'empty', 'enddeclare', 'endfor',
        'endforeach', 'endif', 'endswitch', 'endwhile', 'enum', 'eval', 'exit', 'extends', 'false', 'final', 'finally',
        'float', 'fn', 'for', 'foreach', 'function', 'global', 'goto', 'if', 'implements', 'include', 'instanceof',
        'insteadof', 'int', 'interface', 'isset', 'iterable', 'list', 'match', 'mixed', 'namespace', 'never', 'new',
        'null', 'object', 'or', 'parent', 'print', 'private', 'protected', 'public', 'readonly', 'require', 'return',
        'self', 'static', 'string', 'switch', 'throw', 'trait', 'true', 'try', 'unset', 'use', 'var', 'void', 'while',
        'xor', 'yield',
    ];

    private function __construct() {}

    /**
     * `market_list` -> `MarketList`, `csgoFade` -> `CsgoFade`.
     */
    public static function pascal(string $name): string
    {
        return implode('', array_map(ucfirst(...), explode('_', $name)));
    }

    /**
     * `market_list` -> `marketList`.
     */
    public static function camel(string $name): string
    {
        return lcfirst(self::pascal($name));
    }

    public static function className(string $name): string
    {
        return \in_array(strtolower($name), self::RESERVED_CLASS_NAMES, true) ? $name . 'Type' : $name;
    }

    public static function nullable(string $native): string
    {
        return str_contains($native, '|') ? $native . '|null' : '?' . $native;
    }

    /**
     * PHPDoc block from lines; `null` and empty lines at the edges are dropped. Returns '' when nothing is left.
     *
     * @param list<string|null> $lines
     */
    public static function docBlock(array $lines, string $indent): string
    {
        $text = [];
        foreach ($lines as $line) {
            if ($line !== null) {
                foreach (explode("\n", str_replace('*/', '*\/', trim($line))) as $part) {
                    $text[] = rtrim($part);
                }
            }
        }
        while ($text !== [] && $text[0] === '') {
            array_shift($text);
        }
        while ($text !== [] && $text[\count($text) - 1] === '') {
            array_pop($text);
        }
        if ($text === []) {
            return '';
        }

        $body = implode('', array_map(
            static fn(string $line): string => $line === '' ? $indent . " *\n" : $indent . ' * ' . $line . "\n",
            $text,
        ));

        return $indent . "/**\n" . $body . $indent . " */\n";
    }

    /**
     * A PHPDoc tag for a type the native declaration cannot express (`list<...>`); `null` when the native type says
     * everything already, so no redundant tags are emitted.
     */
    public static function docTag(string $tag, string $docType, string $name = ''): ?string
    {
        if (!str_contains($docType, '<')) {
            return null;
        }

        return rtrim($tag . ' ' . $docType . ' ' . $name);
    }

    /**
     * A nowdoc literal of `text`, body and closing label indented by `indent`. The label is `label`, extended with `_`
     * while a line of the text would close it early (a line starting with the label not followed by a name character).
     */
    public static function nowdoc(string $text, string $label, string $indent): string
    {
        while (preg_match('/^[ \t]*' . $label . '(?![A-Za-z0-9_\x80-\xff])/m', $text) === 1) {
            $label .= '_';
        }

        return "<<<'" . $label . "'\n" . self::indent($text, $indent) . "\n" . $indent . $label;
    }

    /**
     * Prefixes every non-empty line.
     */
    public static function indent(string $text, string $indent): string
    {
        return implode("\n", array_map(
            static fn(string $line): string => $line === '' ? '' : $indent . $line,
            explode("\n", $text),
        ));
    }

    public static function file(string $namespace, string $body): string
    {
        return "<?php\n\n// DO NOT EDIT, generated by tools/codegen-php from schema/partner.graphql and graphql/\n\n"
            . "declare(strict_types=1);\n\nnamespace " . $namespace . ";\n\n" . $body;
    }

    public static function namespaceOf(string $fqcn): string
    {
        $position = strrpos($fqcn, '\\');

        return $position === false ? '' : substr($fqcn, 0, $position);
    }

    public static function shortName(string $fqcn): string
    {
        $position = strrpos($fqcn, '\\');

        return $position === false ? $fqcn : substr($fqcn, $position + 1);
    }
}
